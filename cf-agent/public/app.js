/* 限流：按服务端给的秒数，禁用发送按钮并倒数 */
function startCooldown(sec){
  const until=Date.now()+Math.max(1, sec)*1000;
  const tick=()=>{
    const left=Math.ceil((until-Date.now())/1000);
    if(left<=0){
      clearInterval(COOLDOWN_TIMER); COOLDOWN_TIMER=null;
      if(!BUSY){ send.disabled=false; send.textContent=t('send'); }
      return;
    }
    send.disabled=true;
    send.textContent=left+'s';
  };
  clearInterval(COOLDOWN_TIMER);
  COOLDOWN_TIMER=setInterval(tick, 500);
  tick();
}
function retryAfterOf(r, d){
  const h=Number(r.headers.get('Retry-After'));
  const b=Number(d && d.retryAfter);
  return Number.isFinite(h) && h>0 ? h : (Number.isFinite(b) && b>0 ? b : 60);
}

