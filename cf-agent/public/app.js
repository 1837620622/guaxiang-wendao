/* 章节位置、核对条数、真太阳时、追问里的城市名，切换语言时重画。答案正文不改。 */
function paintMarked(){
  document.querySelectorAll('[data-where]').forEach(node=>{
    const raw = String(node.dataset.where||'');
    if(!/^\d{0,5}:\d{0,5}:\d{0,5}$/.test(raw)) return;
    const parts = raw.split(':');
    const ch = parts[0]||'?';
    const p0 = parts[1]||'?';
    const p1 = parts[2]||'?';
    node.textContent = LANG==='en'
      ? 'Ch. '+ch+' · ¶ '+p0+'–'+p1
      : '第 '+ch+' 章 · 第 '+p0+'–'+p1+' 段';
  });
  document.querySelectorAll('[data-cites]').forEach(node=>{
    const n = String(node.dataset.cites||'0').replace(/\D/g,'') || '0';
    const cached = node.dataset.cached === '1';
    node.textContent = (LANG==='en'?'Passages ':'已核对 ')+n+(cached?(LANG==='en'?' · cached':' · 缓存'):'');
  });
  document.querySelectorAll('[data-goff]').forEach(node=>{
    const name = node.dataset.gname || '';
    const off = Number(node.dataset.goff);
    if(!name || !Number.isFinite(off)) return;
    const body = LANG==='en'
      ? name+' · solar '+(off>=0?'+':'')+off+' min'
      : name+' · 真太阳时 '+(off>=0?'+':'')+off+' 分';
    node.textContent = ' · '+body;
  });
  document.querySelectorAll('a[data-ch]').forEach(node=>{
    const ch = String(node.dataset.ch||'').replace(/\D/g,'');
    if(!ch) return;
    node.textContent = (LANG==='en'?'Ch. ':'第')+ch+(LANG==='en'?' ':'章 ')+(node.dataset.title||'');
  });
  document.querySelectorAll('[data-city]').forEach(node=>{
    const city = node.dataset.city || '';
    if(!city) return;
    node.textContent = t('fu_city').replace('{city}', city);
  });
}

